package com.fix4home.fix4home.model.enums;

/**
 * Article status enumeration
 * Represents the current state of a news article
 */
public enum ArticleStatus {
    DRAFT,       // Article is in draft state (not published)
    PUBLISHED,   // Article has been published and is visible to public
    UNPUBLISHED  // Article has been unpublished (removed from public view)
}

