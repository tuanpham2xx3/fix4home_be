package com.fix4home.fix4home.model.enums;

/**
 * Enum representing the status of a consultation proposal
 */
public enum ConsultationStatus {
    /**
     * Consultation is waiting for customer response
     */
    PENDING,
    
    /**
     * Consultation has been accepted by customer
     */
    ACCEPTED,
    
    /**
     * Consultation has been rejected by customer
     */
    REJECTED
} 